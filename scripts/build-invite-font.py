"""Build the antialiased text masks for the Telegram invitation renderer."""
import base64
import io
import json
from pathlib import Path

from PIL import Image, ImageFont

FONT_DIR = Path('/usr/share/fonts/truetype/liberation')
DEST = Path(__file__).resolve().parents[1] / 'supabase/functions/loopa-bot/invite-font.js'
ATLAS_WIDTH = 768
RANGES = ((0x20, 0x7E), (0xA1, 0x17F), (0x370, 0x3FF), (0x400, 0x4FF))
TITLE_GLYPHS = ''.join(chr(code) for low, high in RANGES for code in range(low, high + 1))
TITLE_GLYPHS += '‘’“”„‹›–—…•№₽€™□'
FACES = (
    ('title', 'LiberationSans-Bold.ttf', 64, TITLE_GLYPHS),
    ('detail', 'LiberationSans-Regular.ttf', 30, 'Ближе, даже на расстоянииYouTubeVK ВидеоRUTUBE 0123456789:·'),
    ('logo', 'LiberationSerif-Regular.ttf', 49, 'LOOPA'),
)

glyphs, pending = {}, []
x, y, row_height = 0, 0, 0
for face, name, size, characters in FACES:
    font = ImageFont.truetype(str(FONT_DIR / name), size)
    glyphs[face] = {}
    for char in dict.fromkeys(characters):
        mask, (left, top) = font.getmask2(char, mode='L', anchor='ls')
        width, height = mask.size
        if x + width > ATLAS_WIDTH:
            x, y, row_height = 0, y + row_height, 0
        glyphs[face][char] = [x, y, width, height, left, top, font.getlength(char)]
        if width and height:
            pending.append((Image.frombytes('L', mask.size, bytes(mask)), x, y))
        x += width
        row_height = max(row_height, height)

atlas = Image.new('L', (ATLAS_WIDTH, y + row_height))
for mask, x, y in pending:
    atlas.paste(mask, (x, y))
out = io.BytesIO()
atlas.save(out, 'PNG', optimize=True)
data = base64.b64encode(out.getvalue()).decode('ascii')
DEST.write_text(
    '// Generated by scripts/build-invite-font.py. See invite-font-license.txt.\n'
    'export const glyphs = ' + json.dumps(glyphs, ensure_ascii=True, separators=(',', ':')) + ';\n'
    'export const atlasPng = [\n' + '\n'.join('  "' + data[i:i+128] + '",' for i in range(0, len(data), 128))
    + '\n].join("");\n',
    encoding='utf-8',
)
